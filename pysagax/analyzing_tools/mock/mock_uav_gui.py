class SimulatedEntryWithLabel:
    def __init__(
        self,
        master: tk.Misc,
        labeltext: str,
        column: int,
        row: int,
        default_value: str = (0, 0, 0),
        width: int = 11,
        padx: int = 5,
        pady: int = 5,
    ) -> None:
        """
        tkinter widget of a label, entry box and tkinter variable combined to be used in frames with columnconfigure
        """
        self.mu = tk.StringVar(value=default_value[0])
        self.sigma = tk.StringVar(value=default_value[1])
        self.delta = tk.StringVar(value=default_value[2])

        self.label = ttk.Label(master, text=labeltext)
        self.mu_label = ttk.Label(master, text="μ:")
        self.sigma_label = ttk.Label(master, text="σ:")
        self.delta_label = ttk.Label(master, text="δ:")
        self.label.grid(column=column, row=row, sticky=tk.W, padx=padx, pady=pady)

        self.mu_label.grid(
            column=column + 1, row=row, sticky=tk.W, padx=padx, pady=pady
        )
        self.sigma_label.grid(
            column=column + 3, row=row, sticky=tk.W, padx=padx, pady=pady
        )
        self.delta_label.grid(
            column=column + 5, row=row, sticky=tk.W, padx=padx, pady=pady
        )

        self.mu_entry = ttk.Entry(master, textvariable=self.mu, width=width)
        self.mu_entry.grid(
            column=column + 2,
            row=row,
            sticky=tk.E + tk.W,
            padx=padx,
            pady=pady,
        )
        self.sigma_entry = ttk.Entry(master, textvariable=self.sigma, width=width)
        self.sigma_entry.grid(
            column=column + 4,
            row=row,
            sticky=tk.E + tk.W,
            padx=padx,
            pady=pady,
        )
        self.delta_entry = ttk.Entry(master, textvariable=self.delta, width=width)
        self.delta_entry.grid(
            column=column + 6,
            row=row,
            sticky=tk.E + tk.W,
            padx=padx,
            pady=pady,
        )

    def get(self, to_radian=False) -> Any:
        if to_radian:
            return tuple(deg2rad(si_to_float(str(p.get()))) for p in (self.mu, self.sigma, self.delta))
        else:
            return tuple(si_to_float(str(p.get())) for p in (self.mu, self.sigma, self.delta))

    def set(self, p: Parameter, to_degree=False):
        if to_degree:
            self.mu.set(round(rad2deg(p.mu), 6))
            self.sigma.set(round(rad2deg(p.sigma), 6))
            self.delta.set(round(rad2deg(p.delta), 6))
        else:
            self.mu.set(round(p.mu, 6))
            self.sigma.set(round(p.sigma, 6))
            self.delta.set(round(p.delta, 6))

    # def set(self, value: Any) -> Any:
    #     return (
    #         self.mu.set(value=[0]),
    #         self.sigma.set(value=[1]),
    #         self.delta.set(value=value[2]),
    #     )

    def destroy(self) -> None:
        self.label.destroy()
        self.mu_label.destroy()
        self.sigma_label.destroy()
        self.delta_label.destroy()
        self.mu_entry.destroy()
        self.sigma_entry.destroy()
        self.delta_entry.destroy()
        # return super().destroy()

    def configure(self, **kwargs):
        for entry in [self.mu_entry, self.sigma_entry, self.delta_entry]:
            entry.configure(**kwargs)


