    def monitor_generated_packets(self):
        while True:
            try:
                # for 
                packet = self.queue_in.get(timeout=0)
                self.latest_generated__measurement = packet
            except queue.Empty:
                sleep(0.1)
            # print("run")
        pass

    def gui_updater(self):
        self.root.after(100, self.gui_updater)
        if not self.edit_mode:
            self.refresh_entries(self.latest_generated__measurement)
            # sleep(.1)

    def refresh_entries(self, sm:SimulatedMeasurement):
        self.stream_id.set(sm.stream_id)
        self.config_id.set(sm.config_id)
        self.yaw.set(sm.heading_data.yaw, True)
        self.pitch.set(sm.heading_data.pitch, True)
        self.roll.set(sm.heading_data.roll, True)
        self.gps_lat.set(sm.heading_data.gps_lat)
        self.gps_lon.set(sm.heading_data.gps_lon)
        self.altitude.set(sm.heading_data.altitude)
        self.offset.set(sm.heading_data.offset) #TODO: to degree and radian

        if not len(sm.detections):
            # fill with default
            sm.detections = [SimulatedDetection()]
        self.event_id.set(sm.detections[0].event_id)
        self.roi_id.set(sm.detections[0].roi_id)
        self.frequency.set(sm.detections[0].frequency)
        self.azimuth.set(sm.detections[0].azimuth, True)
        self.mean_azimuth.set(sm.detections[0].mean_azimuth, True)
        self.elevation.set(sm.detections[0].elevation, True)
        self.mean_elevation.set(sm.detections[0].mean_elevation, True)
        self.deviation.set(sm.detections[0].deviation, True)

